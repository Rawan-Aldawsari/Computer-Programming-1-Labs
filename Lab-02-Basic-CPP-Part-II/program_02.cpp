
#include <iostream>
using namespace std;

int main()
{
    int a = 1, b = 2;

    cout << (a < b);
    cout << endl;

    cout << (a > b);
    cout << endl;

    cout << (++a == b);
    cout << endl;

    cout << (a <= b);
    cout << endl;

    cout << (a >= b);
    cout << endl;

    system("PAUSE");
    return 0;
}