
#include <iostream>
using namespace std;

int main()
{
    int a = 2;

    cout << ++a;
    cout << endl;

    cout << a++;
    cout << endl;

    cout << a;
    cout << endl;

    cout << --a;
    cout << endl;

    cout << a--;
    cout << endl;

    cout << a;
    cout << endl;

    system("PAUSE");
    return 0;
}